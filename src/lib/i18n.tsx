type Dict = typeof DICT.en
type Key = keyof Dict

interface I18nCtx {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: Key, params?: Record<string, string | number>) => string
}

const Ctx = createContext<I18nCtx | null>(null)

const STORAGE_KEY = 'ccd.locale'

function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'ko'
  const stored = window.localStorage.getItem(STORAGE_KEY) as Locale | null
  if (stored === 'en' || stored === 'ko') return stored
  const nav = window.navigator.language?.slice(0, 2)
  return nav === 'ko' ? 'ko' : 'en'
}

function interpolate(s: string, params?: Record<string, string | number>) {
  if (!params) return s
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`))
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectLocale())

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale)
    document.documentElement.lang = locale
  }, [locale])

  const value = useMemo<I18nCtx>(() => ({
    locale,
    setLocale: setLocaleState,
    t: (key, params) => {
      const dict = DICT[locale] as Record<string, string>
      const fallback = DICT.en as Record<string, string>
      const raw = dict[key] ?? fallback[key] ?? String(key)
      return interpolate(raw, params)
    },
  }), [locale])

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

export function useT() {
  return useI18n().t
}
